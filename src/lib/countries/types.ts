export interface City {
  name: string
  lat: number
  lon: number
  fact: string
}

export interface Site extends City {
  /** The commune it stands in: at most one site per commune, to keep the map readable. */
  city: string
}

/** A culinary specialty, placed where it comes from (one specialty per town, to keep the map readable). */
export interface Food extends City {
  /** The town or area it is tied to. */
  place: string
}

export interface RiverShape {
  id: string
  /** Where the marker number / name label sits (map units). */
  label: [number, number]
  /** The course, in map units (a river can be split in several pieces). */
  lines: [number, number][][]
}

/** Generated by scripts/country/build-map.mjs. */
export interface MapGeometry {
  /** Longitude of the left edge, latitude of the top edge. */
  lon0: number
  latMax: number
  /** Longitude compression (cos of the middle latitude) and map units per degree of latitude. */
  k: number
  scale: number
  width: number
  height: number
  /** SVG path of the country's outline. */
  outline: string
  rivers: RiverShape[]
}

export interface RiverInfo {
  name: string
  fact: string
}

/** Every piece of text the game shows. `{country}`, `{n}`, `{round}`, `{score}`, `{link}` are filled in at runtime. */
export interface Strings {
  /** Contains `{country}` and `{kinds}` (the kinds the country has, e.g. "villes et monuments"). */
  title: string
  /** One short line (it must fit on a phone): what to do. */
  lead: string
  scoreLine: string
  hint: string
  /** Shown under a specialty's name once placed; contains `{place}`. */
  originLabel: string
  /** Shown under a landmark's name once placed; contains `{place}` (the town it stands in). */
  siteOriginLabel: string
  nextRound: string
  mapLabel: string
  namesLabel: string
  kindLabels: { city: string; site: string; river: string; food: string }
  /** Plural names, used in the title and the map description. */
  kindNames: { city: string; site: string; river: string; food: string }
  /** One very short phrase per kind: its marker symbol and name, e.g. "● ville" (●, ◆, ▬, ■ are the shapes on the map). */
  legend: { city: string; site: string; river: string; food: string }
  /** The word before the last item of a list ("et" / "and"). */
  listAnd: string
  aboutTitle: string
  aboutText: string
  /** Contains `{link}`, replaced by a link to Natural Earth. */
  aboutSource: string
}

/** The written part of a country: what a person (or Claude) authors. */
export interface CountryContent {
  id: string
  /** Country name in the legend language. */
  name: string
  /** Legend language (ISO 639-1). */
  lang: string
  cities: City[]
  sites: Site[]
  /** Culinary specialties tied to a place (optional: a country may have none). */
  foods?: Food[]
  /** Name and fact for every river of the generated map, by river id. */
  rivers: Record<string, RiverInfo>
  strings: Strings
}

export interface CountryData extends CountryContent {
  map: MapGeometry
}

/** Small, loaded eagerly for the menu; the rest of the country is loaded when its game opens. */
export interface CountryMeta {
  id: string
  emoji: string
  name: string
  description: string
}
