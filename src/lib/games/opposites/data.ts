import type { TitleType } from '../../providers/types'

/** Language of the title the player types (and of its opposite). */
export type TitleLang = 'fr' | 'other'

export interface OppositeEntry {
  /** Title the player must find, in `lang` (French release title for 'fr'). Shown at the end. */
  title: string
  /** The same title with its main words replaced by their opposites, same language. */
  opposite: string
  lang: TitleLang
  /** The IMDb / TV CSV row this is about (poster, year, stars): exact Series_Title + year. */
  ref: { type: TitleType; title: string; year: number }
  /** Other accepted answers (alternative spellings / Québec title…). The CSV title is always accepted. */
  aliases?: string[]
}

type Ref = OppositeEntry['ref']
const movie = (title: string, year: number): Ref => ({ type: 'movie', title, year })
const tv = (title: string, year: number): Ref => ({ type: 'tv', title, year })
const fr = (title: string, opposite: string, ref: Ref, aliases?: string[]): OppositeEntry =>
  aliases ? { title, opposite, lang: 'fr', ref, aliases } : { title, opposite, lang: 'fr', ref }
const en = (title: string, opposite: string, ref: Ref, aliases?: string[]): OppositeEntry =>
  aliases ? { title, opposite, lang: 'other', ref, aliases } : { title, opposite, lang: 'other', ref }

